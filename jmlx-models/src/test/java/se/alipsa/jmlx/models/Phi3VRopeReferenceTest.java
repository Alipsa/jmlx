package se.alipsa.jmlx.models;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.file.Path;
import org.junit.jupiter.api.Test;
import se.alipsa.jmlx.core.MLX;
import se.alipsa.jmlx.core.MLXArray;
import se.alipsa.jmlx.ffi.EnabledIfNativeAvailable;
import se.alipsa.jmlx.memory.MLXScope;
import se.alipsa.jmlx.nn.RopeSpec;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.ObjectMapper;

/**
 * Differential NTK-Su RoPE against the pinned bundled reference: the pure period/selection check
 * runs on every host, and the rotated-output check runs through the MLX kernel where the native
 * runtime is available. The golden (tools/hf-reference/goldens/phi3v-rope.json) was generated by
 * tools/hf-reference/phi3v_rope.py (never Gradle-invoked) from the pinned
 * microsoft/Phi-3.5-vision-instruct config and its bundled Phi3SuScaledRotaryEmbedding.
 */
class Phi3VRopeReferenceTest {
  private static final ObjectMapper MAPPER = new ObjectMapper();

  @Test
  void periodsAndTableSelectionMatchTheBundledReference() throws Exception {
    JsonNode golden = golden();
    assertEquals(96, golden.path("head_dim").asInt());
    RopeSpec spec = spec(golden);
    assertEquals(golden.path("attention_scaling").asDouble(), spec.attentionScaling(), 1e-6);
    assertFalse(spec.isStatic());
    double[] boundaryShort = null;
    double[] boundaryLong = null;
    for (JsonNode table : golden.path("tables")) {
      int seqLen = table.path("seq_len").asInt();
      double[] periods = spec.frequencies(96, seqLen);
      JsonNode invFreq = table.path("inv_freq");
      assertEquals(48, periods.length);
      for (int i = 0; i < periods.length; i++) {
        double expectedPeriod = 1 / invFreq.get(i).asDouble();
        assertEquals(
            expectedPeriod,
            periods[i],
            Math.max(1e-5, expectedPeriod * 1e-6),
            "seq_len=" + seqLen + " i=" + i);
      }
      if (seqLen == 4096) {
        boundaryShort = periods;
      } else if (seqLen == 4097) {
        boundaryLong = periods;
      }
    }
    // The two boundary tables must be distinct in the golden itself (a degenerate golden where
    // short and long agree would make the boundary selection untestable).
    assertFalse(boundaryShort == null || boundaryLong == null);
    boolean differs = false;
    for (int i = 0; i < boundaryShort.length; i++) {
      differs |= Math.abs(boundaryShort[i] - boundaryLong[i]) > 1e-4;
    }
    assertTrue(differs, "golden short and long tables are identical at the 4096/4097 boundary");
  }

  @Test
  @EnabledIfNativeAvailable
  void rotatedOutputsMatchTheBundledReference() throws Exception {
    JsonNode golden = golden();
    RopeSpec spec = spec(golden);
    try (MLXScope scope = new MLXScope()) {
      for (JsonNode sample : golden.path("samples")) {
        int offset = sample.path("offset").asInt();
        float[] input = new float[96];
        float[] expected = new float[96];
        for (int i = 0; i < 96; i++) {
          input[i] = (float) sample.path("input").get(i).asDouble();
          expected[i] = (float) sample.path("rotated").get(i).asDouble();
        }
        MLXArray x = MLX.array(scope, input, new int[] {1, 1, 1, 96});
        float[] actual = spec.apply(x, 96, offset, null).toFloatArray();
        assertArrayEquals(
            expected, actual, (float) sample.path("tolerance").asDouble(), "offset=" + offset);
      }
    }
  }

  private static RopeSpec spec(JsonNode golden) {
    return new RopeSpec.Su(
        (float) golden.path("theta").asDouble(),
        golden.path("max_positions").asInt(),
        golden.path("original_max_positions").asInt(),
        floats(golden.path("short_factor")),
        floats(golden.path("long_factor")));
  }

  private static float[] floats(JsonNode values) {
    float[] result = new float[values.size()];
    for (int i = 0; i < result.length; i++) {
      result[i] = (float) values.get(i).asDouble();
    }
    return result;
  }

  private static Path goldenPath() {
    return Path.of(
            System.getProperty("jmlx.repository.root"),
            "tools",
            "hf-reference",
            "goldens",
            "phi3v-rope.json")
        .toAbsolutePath();
  }

  private static JsonNode golden() throws Exception {
    return MAPPER.readTree(goldenPath().toFile());
  }
}
