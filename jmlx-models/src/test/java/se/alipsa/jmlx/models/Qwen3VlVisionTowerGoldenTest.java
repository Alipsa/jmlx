/**
 * Strict CPU-HF float32 golden for the WP5 vision tower ({@code
 * req/plans/phase7-3b-reference-findings.md} §11): the tiny synthetic {@code
 * checkpoints/qwen3vl-vision} checkpoint (bf16 {@code model.visual.*} weights, four deterministic
 * PNGs, packed 144-patch processor run) against {@code qwen3vl-vision-wp5.json}. The reference
 * (pinned transformers 4.57.6 / torch 2.6.0+cpu venv, CPU, float32, seed 20261021, generated by
 * {@code tools/hf-reference/qwen3vl_vision.py}) captures the interpolated position embedding, the
 * patch-embedding convolution output, blocks 0/1/3/5, the main merger and all three DeepStack
 * levels; the golden stores them rounded to 7 significant digits, so the comparisons use the
 * established 1e-4 golden tolerance while the bit-exact arithmetic probes (linspace, the
 * pos-embedding bilinear sample) are checked at bit level.
 */
@Tag("full-float32")
@EnabledIfNativeAvailable
class Qwen3VlVisionTowerGoldenTest {

  /**
   * The golden's 7-significant-digit storage tolerance (see qwen3vl_vision.py's {@code rounded}).
   */
  private static final float TOLERANCE = 1e-4f;

  static Path directory() {
    return Path.of(
        System.getProperty("jmlx.repository.root"),
        "tools/hf-reference/goldens/checkpoints/qwen3vl-vision");
  }

  static JsonNode golden() throws Exception {
    return JsonFiles.read(directory().getParent().getParent().resolve("qwen3vl-vision-wp5.json"));
  }

  static Qwen3VlImageProcessor processor() {
    // Mirrors the golden's provenance.processor (the pinned 4.57.6 slow Qwen2VL processor
    // options); the shared WP2 qwen3vl image-oracle fixtures already pin this exact port. The
    // artifact's 12,845,056-pixel ceiling exceeds the port's default 4,096-row hard budget, so
    // the documented programmatic rawRowBudget override lifts the cap (12,845,056 / 16^2); every
    // golden image is far below both, so the cap never engages for this fixture.
    return new Qwen3VlImageProcessor(
        Qwen3VlProcessorConfig.builder()
            .patchSize(16)
            .temporalPatchSize(2)
            .mergeSize(2)
            .minPixels(3136)
            .maxPixels(12845056)
            .rawRowBudget(50176)
            .imageMean(new float[] {0.5f, 0.5f, 0.5f})
            .imageStd(new float[] {0.5f, 0.5f, 0.5f})
            .build());
  }

  static Qwen3VlVisionTower buildTower(MLXScope scope, JsonNode golden) throws Exception {
    JsonNode config = golden.required("provenance").required("config");
    int depth = config.required("depth").intValue();
    int[] deepstackIndexes = ints(config.required("deepstack_visual_indexes"));
    Map<String, MLXArray> checkpoint =
        MLXIO.loadSafetensors(scope, directory().resolve("model.safetensors").toString()).tensors();
    Map<String, MLXArray> weights =
        Qwen3VlVisionTower.visionWeights(checkpoint, depth, deepstackIndexes);
    return new Qwen3VlVisionTower(
        scope, config.required("num_heads").intValue(), weights, deepstackIndexes);
  }

  @Test
  void towerMatchesHfGolden() throws Exception {
    JsonNode golden = golden();
    JsonNode config = golden.required("provenance").required("config");
    int depth = config.required("depth").intValue();
    int numHeads = config.required("num_heads").intValue();
    int[] deepstackIndexes = ints(config.required("deepstack_visual_indexes"));
    List<JsonNode> cases = new ArrayList<>();
    golden.required("cases").forEach(cases::add);

    try (MLXScope scope = new MLXScope()) {
      JsonNode checkpointConfig = JsonFiles.read(directory().resolve("config.json"));
      assertEquals(depth, checkpointConfig.required("depth").intValue(), "checkpoint depth");
      assertEquals(numHeads, checkpointConfig.required("num_heads").intValue(), "checkpoint heads");
      assertArrayEquals(
          deepstackIndexes,
          ints(checkpointConfig.required("deepstack_visual_indexes")),
          "checkpoint deepstack indexes");

      Qwen3VlVisionTower tower = buildTower(scope, golden);
      assertEquals(depth, tower.depth(), "tower depth");
      assertEquals(numHeads, tower.numHeads(), "tower heads");
      assertEquals(config.required("hidden_size").intValue(), tower.hidden(), "tower hidden");
      assertEquals(
          config.required("num_position_embeddings").intValue(),
          tower.gridSide() * tower.gridSide(),
          "tower position grid");
      assertEquals(
          config.required("spatial_merge_size").intValue(),
          tower.spatialMergeSize(),
          "tower merge");
      assertEquals(
          config.required("out_hidden_size").intValue(), tower.outHiddenSize(), "tower out width");
      assertArrayEquals(deepstackIndexes, tower.deepstackIndexes(), "tower deepstack indexes");

      Qwen3VlImageProcessor processor = processor();
      List<Qwen3VlImageProcessorResult> results = new ArrayList<>(cases.size());
      for (JsonNode c : cases) {
        String name = c.required("name").asString();
        Qwen3VlImageProcessorResult result =
            processor.processFile(
                directory().resolve(c.required("file").asString()), ImageDecodeLimits.DEFAULTS);
        assertArrayEquals(ints(c.required("grid")), result.gridThw(), name + " grid");
        assertEquals(
            c.required("n_patches").intValue(), result.rawPatchRows(), name + " n_patches");
        assertEquals(
            c.required("merged_rows").intValue(), result.mergedRowCount(), name + " merged_rows");
        // The per-case pixel_values digest pins the whole preprocessing chain byte-for-byte
        // against the reference's packed processor output slice (row-major float32 bytes).
        assertEquals(
            c.required("pixel_values_sha256").asString(),
            sha256OfFloats(result.values()),
            name + " pixel_values sha256");
        results.add(result);
      }

      // The tower's module scope is the test scope itself, so it is a legal target; the
      // hoisted features and captures live in it until the test scope closes below.
      Qwen3VlVisionTower.ForwardCaptures captures = tower.forwardForTest(scope, results);

      // The final merged and DeepStack arrays are stored once over the packed rows (image
      // order); the tower concatenates its per-image rows on axis 0 the same way.
      JsonNode packed = golden.required("packed");
      for (String key : new String[] {"merger", "deepstack0", "deepstack1", "deepstack2"}) {
        JsonNode entry = packed.required(key);
        MLXArray actual;
        if (key.equals("merger")) {
          actual = captures.features().merged();
        } else {
          int level = Integer.parseInt(key.substring("deepstack".length()));
          actual = captures.features().deepstackLevels().get(level);
        }
        assertArrayEquals(ints(entry.required("shape")), actual.shape(), key + " shape");
        assertArrayEquals(
            floats(entry.required("values")),
            actual.toFloatArray(),
            TOLERANCE,
            key + " must match the reference's packed rows");
      }

      // The per-image captures slice the same packed tensors; the merged-row offsets must be
      // cumulative in input order (square 16 + wide 6 + tall 6 + narrow 8 = 36).
      int mergedRowOffset = 0;
      for (int i = 0; i < cases.size(); i++) {
        JsonNode c = cases.get(i);
        String name = c.required("name").asString();
        assertEquals(
            mergedRowOffset,
            c.required("merged_row_offset").intValue(),
            name + " merged_row_offset");
        mergedRowOffset += c.required("merged_rows").intValue();
        Qwen3VlVisionTower.ImageCaptures capture = captures.images().get(i);
        List<MLXArray> blocks = List.of(capture.blockOutputs());
        assertEquals(1 + deepstackIndexes.length, blocks.size(), name + " block capture count");
        assertArrayEquals(
            floats(c.required("captures").required("pos_embed_interpolated").required("values")),
            capture.posEmbedInterpolated().toFloatArray(),
            TOLERANCE,
            name + " pos_embed_interpolated");
        assertArrayEquals(
            floats(c.required("captures").required("patch_embed").required("values")),
            capture.patchEmbed().toFloatArray(),
            TOLERANCE,
            name + " patch_embed");
        assertArrayEquals(
            floats(c.required("captures").required("block0").required("values")),
            blocks.get(0).toFloatArray(),
            TOLERANCE,
            name + " block0");
        for (int j = 0; j < deepstackIndexes.length; j++) {
          assertArrayEquals(
              floats(
                  c.required("captures")
                      .required("block" + deepstackIndexes[j])
                      .required("values")),
              blocks.get(j + 1).toFloatArray(),
              TOLERANCE,
              name + " block" + deepstackIndexes[j]);
        }
      }
      assertEquals(36, mergedRowOffset, "total merged rows");
    }
  }

  @Test
  void linspaceProbesBitMatchPinnedTorch() throws Exception {
    JsonNode golden = golden();
    // The tiny tower's num_position_embeddings 64 gives num_grid_per_side 8, the probe's side.
    int side =
        (int)
            Math.sqrt(
                golden
                    .required("provenance")
                    .required("config")
                    .required("num_position_embeddings")
                    .intValue());
    for (JsonNode probe : golden.required("probes").required("linspace")) {
      int n = probe.required("n").intValue();
      for (int i = 0; i < n; i++) {
        long bits = Long.parseUnsignedLong(probe.required("values_hex").get(i).asString(), 16);
        double pinned = Double.longBitsToDouble(bits);
        // The probe stores the float32 value widened to double; the port must reproduce the
        // float32 rounding of the pinned torch linspace kernel bits exactly.
        assertEquals(
            Float.floatToRawIntBits((float) pinned),
            Float.floatToRawIntBits(Qwen3VlVisionTower.linspaceValue(side, n, i)),
            "linspace(" + side + ", " + n + ", " + i + ") must bit-match the pinned torch bits");
      }
    }
  }

  @Test
  void posEmbedSampleCornerDataMatchesTower() throws Exception {
    JsonNode golden = golden();
    JsonNode samples = golden.required("probes").required("pos_embed_sample");
    int merge =
        golden.required("provenance").required("config").required("spatial_merge_size").intValue();
    try (MLXScope scope = new MLXScope()) {
      Qwen3VlVisionTower tower = buildTower(scope, golden);
      Qwen3VlImageProcessor processor = processor();
      for (JsonNode c : golden.required("cases")) {
        if (!samples.has(c.required("name").asString())) {
          continue;
        }
        JsonNode s = samples.required(c.required("name").asString());
        String name = c.required("name").asString();
        int[] grid = ints(c.required("grid"));
        int h = grid[1];
        int w = grid[2];
        int[] patch = ints(s.required("grid"));
        int ph = patch[0];
        int pw = patch[1];
        // The reference selected the first patch in merge-block order whose row AND column
        // linspace values are both fractional; row-major row index in that order.
        final int rowInImage =
            (ph / merge * (w / merge) + pw / merge) * merge * merge
                + (ph % merge) * merge
                + (pw % merge);

        Qwen3VlImageProcessorResult result =
            processor.processFile(
                directory().resolve(c.required("file").asString()), ImageDecodeLimits.DEFAULTS);
        final Qwen3VlVisionTower.ImageCaptures capture =
            tower.forwardForTest(scope, List.of(result)).images().get(0);

        // The tower's bilinear corner indices for that patch must be the reference's exactly.
        Qwen3VlVisionTower.PositionLookup lookup =
            Qwen3VlVisionTower.positionLookup(h, w, tower.gridSide());
        int k = ph * w + pw;
        List<Integer> flat = new ArrayList<>();
        for (int corner = 0; corner < 4; corner++) {
          flat.add(lookup.cornerIndices()[corner][k]);
        }
        List<Integer> expected = new ArrayList<>();
        for (JsonNode corner : s.required("corner_indices")) {
          expected.add(corner.intValue());
        }
        assertEquals(expected, flat, name + " corner indices");

        // The tower's float32-pipeline corner weights and the golden's double-pipeline hex
        // differ by at most one float32 ulp (the probe script recomputes in double before
        // casting); 1e-6 absolute absorbs that and still catches a wrong formula.
        for (int corner = 0; corner < 4; corner++) {
          float pinned =
              Float.intBitsToFloat(
                  Integer.parseUnsignedInt(
                      s.required("corner_weights_hex").get(corner).asString(), 16));
          float actual = lookup.cornerWeights()[corner][k];
          assertTrue(
              Math.abs(actual - pinned) <= 1e-6,
              name + " corner weight " + corner + ": " + actual + " vs pinned " + pinned);
        }

        // The interpolated row the reference sampled must match the tower's row bit-for-bit
        // within the golden's 7-significant-digit storage.
        float[] row = capture.posEmbedInterpolated().toFloatArray();
        assertEquals(h * w * tower.hidden(), row.length, name + " pos_embed row count");
        List<Float> expectedRow = new ArrayList<>();
        for (JsonNode v : s.required("expected_row")) {
          expectedRow.add(v.floatValue());
        }
        for (int j = 0; j < expectedRow.size(); j++) {
          float expectedValue = expectedRow.get(j);
          assertTrue(
              Math.abs(row[rowInImage * tower.hidden() + j] - expectedValue) <= TOLERANCE,
              name
                  + " pos_embed sample row["
                  + rowInImage
                  + "]["
                  + j
                  + "]: "
                  + row[rowInImage * tower.hidden() + j]
                  + " vs "
                  + expectedValue);
        }
      }
    }
  }

  static int[] ints(JsonNode node) {
    List<Integer> values = new ArrayList<>();
    node.forEach(v -> values.add(v.intValue()));
    return values.stream().mapToInt(Integer::intValue).toArray();
  }

  static float[] floats(JsonNode node) {
    List<Float> values = new ArrayList<>();
    flatten(node, values);
    float[] result = new float[values.size()];
    for (int i = 0; i < result.length; i++) {
      result[i] = values.get(i);
    }
    return result;
  }

  private static void flatten(JsonNode node, List<Float> values) {
    if (node.isArray()) {
      node.forEach(v -> flatten(v, values));
    } else {
      values.add(node.floatValue());
    }
  }

  /**
   * The SHA-256 of the row-major float32 bytes (little-endian, as numpy's {@code tobytes} emits).
   */
  private static String sha256OfFloats(float[] values) throws Exception {
    ByteBuffer buffer = ByteBuffer.allocate(values.length * 4).order(ByteOrder.LITTLE_ENDIAN);
    buffer.asFloatBuffer().put(values);
    byte[] digest = MessageDigest.getInstance("SHA-256").digest(buffer.array());
    StringBuilder hex = new StringBuilder(digest.length * 2);
    for (byte b : digest) {
      hex.append(Character.forDigit((b >> 4) & 0xF, 16)).append(Character.forDigit(b & 0xF, 16));
    }
    return hex.toString();
  }
}
