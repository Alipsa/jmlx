package se.alipsa.jmlx.nn;

import java.lang.classfile.ClassFile;
import java.lang.classfile.CodeElement;
import java.lang.classfile.CodeTransform;
import java.lang.classfile.MethodModel;
import java.lang.classfile.MethodTransform;
import java.lang.classfile.instruction.InvokeInstruction;
import java.lang.constant.ClassDesc;
import java.lang.constant.ConstantDescs;
import java.lang.constant.MethodTypeDesc;
import java.lang.instrument.ClassFileTransformer;
import java.lang.instrument.Instrumentation;
import java.security.ProtectionDomain;
import java.util.Map;
import java.util.TreeMap;

/**
 * Opt-in benchmark agent: counts actual generated MethodHandle downcalls in a separate JVM run.
 *
 * <p>Shared by the opt-in native-call-count consumers (the Qwen3.5 delta benchmark, the decode
 * baseline diagnostics): {@code premain} installs an entry counter on every generated {@code mlx_h}
 * downcall method at class-load time, without editing any generated source or reference math.
 * Recording is windowed — {@link #start()} opens a window (resetting the counters) and {@link
 * #stop()} closes it and returns the attempted-downcall counts by exact binding name. Counting-run
 * timings are invalid performance evidence, and the counts describe attempted mlx-c API downcalls,
 * not Metal dispatches, kernels or GPU synchronizations.
 *
 * <p>Transform failures are recorded in a property and surfaced by {@link #start()} and {@link
 * #stop()} (an instrumented run must fail, never count silently). The descriptor of every
 * instrumented downcall is recorded as well ({@link #signatures()}), so a consumer can group counts
 * by downcall signature class without re-reading the generated bytecode.
 */
public final class BindingCounterAgent {
  private static final String PREFIX = "jmlx.binding.count.";
  private static final String INSTALLED = "jmlx.binding.installed";
  private static final String RECORDING = "jmlx.binding.recording";
  private static final String FAILURE = "jmlx.binding.failure";
  private static final String SIGNATURES = "jmlx.binding.signatures";

  private BindingCounterAgent() {}

  /** Installs entry instrumentation without editing any generated source or reference math. */
  public static void premain(String arguments, Instrumentation instrumentation) {
    System.setProperty(INSTALLED, "true");
    instrumentation.addTransformer(
        new ClassFileTransformer() {
          @Override
          public byte[] transform(
              ClassLoader loader,
              String name,
              Class<?> type,
              ProtectionDomain domain,
              byte[] bytes) {
            if (name == null || !name.startsWith("se/alipsa/jmlx/ffi/mlx_h")) {
              return null;
            }
            try {
              ClassFile classFile = ClassFile.of();
              return classFile.transformClass(
                  classFile.parse(bytes),
                  (builder, element) -> {
                    if (element instanceof MethodModel method && isDowncall(method)) {
                      recordSignature(method);
                      builder.transformMethod(
                          method,
                          MethodTransform.transformingCode(
                              CodeTransform.ofStateful(
                                  () ->
                                      new CodeTransform() {
                                        private boolean first = true;

                                        @Override
                                        public void accept(
                                            java.lang.classfile.CodeBuilder code,
                                            CodeElement instruction) {
                                          if (first) {
                                            code.ldc(method.methodName().stringValue())
                                                .invokestatic(
                                                    ClassDesc.of(
                                                        BindingCounterAgent.class.getName()),
                                                    "hit",
                                                    MethodTypeDesc.of(
                                                        ConstantDescs.CD_void,
                                                        ConstantDescs.CD_String));
                                            first = false;
                                          }
                                          code.with(instruction);
                                        }
                                      })));
                    } else {
                      builder.with(element);
                    }
                  });
            } catch (RuntimeException | Error error) {
              System.setProperty(FAILURE, error.toString());
              return null;
            }
          }
        });
  }

  private static boolean isDowncall(MethodModel method) {
    return method.methodName().stringValue().matches("mlx_[a-z0-9_]+")
        && method
            .code()
            .map(
                code ->
                    code.elementStream()
                        .anyMatch(
                            element ->
                                element instanceof InvokeInstruction invoke
                                    && invoke.name().equalsString("invokeExact")))
            .orElse(false);
  }

  /** Records the instrumented downcall's JVM descriptor, keyed by its binding name. */
  private static void recordSignature(MethodModel method) {
    String line = method.methodName().stringValue() + "\t" + method.methodType().stringValue();
    synchronized (System.getProperties()) {
      String existing = System.getProperty(SIGNATURES, "");
      System.setProperty(SIGNATURES, existing.isEmpty() ? line : existing + "\n" + line);
    }
  }

  /** Called only by instrumented generated downcall bodies. */
  public static void hit(String name) {
    if (Boolean.getBoolean(RECORDING)) {
      synchronized (System.getProperties()) {
        String key = PREFIX + name;
        long count = Long.parseLong(System.getProperty(key, "0"));
        System.setProperty(key, Long.toString(count + 1));
      }
    }
  }

  /** Whether this JVM was explicitly launched with this benchmark agent. */
  public static boolean isInstalled() {
    return Boolean.getBoolean(INSTALLED);
  }

  /**
   * The recorded transform failure, or null. A non-null value means the instrumented run must fail:
   * some generated downcalls would be silently uncounted.
   */
  public static String failureReason() {
    return System.getProperty(FAILURE);
  }

  /**
   * The JVM descriptor of every instrumented downcall, by exact binding name (empty when the agent
   * is not installed or the generated class has not loaded yet).
   */
  public static Map<String, String> signatures() {
    String raw = System.getProperty(SIGNATURES, "");
    Map<String, String> result = new TreeMap<>();
    if (raw.isEmpty()) {
      return result;
    }
    for (String line : raw.split("\n")) {
      int tab = line.indexOf('\t');
      if (tab > 0) {
        result.put(line.substring(0, tab), line.substring(tab + 1));
      }
    }
    return result;
  }

  /** Begins one counted sample; callers never use that sample for timing comparisons. */
  public static void start() {
    if (!isInstalled() || System.getProperty(FAILURE) != null) {
      throw new IllegalStateException(
          "Binding-count agent was not installed successfully: " + System.getProperty(FAILURE));
    }
    // String properties share the counter across Gradle's isolated test/agent classloaders.
    System.getProperties().stringPropertyNames().stream()
        .filter(key -> key.startsWith(PREFIX))
        .forEach(System::clearProperty);
    System.setProperty(RECORDING, "true");
  }

  /** Ends a sample and returns attempted native downcall counts by exact binding name. */
  public static Map<String, Long> stop() {
    System.setProperty(RECORDING, "false");
    if (System.getProperty(FAILURE) != null) {
      throw new IllegalStateException(
          "Binding instrumentation failed: " + System.getProperty(FAILURE));
    }
    Map<String, Long> result = new TreeMap<>();
    System.getProperties().stringPropertyNames().stream()
        .filter(key -> key.startsWith(PREFIX))
        .forEach(
            key ->
                result.put(
                    key.substring(PREFIX.length()), Long.parseLong(System.getProperty(key))));
    return result;
  }
}
