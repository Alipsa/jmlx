"""Publication comparison must retain dependency, provenance and archive content changes."""

import copy
import io
import json
import sys
import subprocess
import warnings
import tempfile
import unittest
import zipfile
from pathlib import Path
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import compare_publications as C


class ComparePublicationsTest(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.central = Path(self.temp.name) / "central"
        self.candidate = Path(self.temp.name) / "candidate"
        for directory in (self.central, self.candidate):
            directory.mkdir()
            self.write_archive(directory)
        self.metadata = {"createdBy": {"gradle": {"version": "9.7.0"}}, "variants": [
            {"name": "runtimeElements", "dependencies": [{"version": "3.1.2"}], "files": []}]}

    def write_archive(self, directory, *, reverse=False, content=b"class bytes"):
        with zipfile.ZipFile(directory / "fixture.jar", "w") as archive:
            for name in sorted(("LICENSE", "Example.class"), reverse=reverse):
                info = zipfile.ZipInfo(name, (2026 if reverse else 2025, 1, 1, 0, 0, 0))
                archive.writestr(info, content if name.endswith(".class") else b"license bytes")

    def write_module(self, directory, *, gradle="9.7.0", dependency="3.1.2"):
        metadata = copy.deepcopy(self.metadata)
        data = (directory / "fixture.jar").read_bytes()
        metadata["createdBy"]["gradle"]["version"] = gradle
        variant = metadata["variants"][0]
        variant["dependencies"][0]["version"] = dependency
        variant["files"] = [{"name": "fixture.jar", "url": "fixture.jar", "size": len(data),
                             **{algorithm: C.digest(data, algorithm)
                                for algorithm in ("sha512", "sha256", "sha1", "md5")}}]
        (directory / "fixture.module").write_text(json.dumps(metadata, indent=2) + "\n")

    def test_only_archive_order_timestamps_and_matching_metadata_hashes_are_normalized(self):
        self.write_archive(self.candidate, reverse=True)
        for directory in (self.central, self.candidate):
            self.write_module(directory)
        results = C.compare(self.central, self.candidate)["artifacts"]
        self.assertTrue(all(result["equal"] for result in results.values()))
        self.assertNotEqual(results["fixture.jar"]["rawSha256"]["central"],
                            results["fixture.jar"]["rawSha256"]["candidate"])

    def test_dependency_and_gradle_provenance_changes_survive_normalization(self):
        self.write_module(self.central)
        for change in ({"gradle": "9.9.0"}, {"dependency": "3.3.0"}):
            with self.subTest(change=change):
                self.write_module(self.candidate, **change)
                self.assertFalse(C.compare(self.central, self.candidate)["artifacts"]["fixture.module"]["equal"])

    def test_class_and_documentation_changes_survive(self):
        self.write_archive(self.candidate, content=b"different class bytes")
        for directory in (self.central, self.candidate):
            (directory / "fixture.pom").write_text("<project/>")
        results = C.compare(self.central, self.candidate)["artifacts"]
        self.assertEqual(results["fixture.jar"]["changedEntries"], ["Example.class"])
        self.assertFalse(results["fixture.jar"]["equal"])
        for directory, version in ((self.central, 21), (self.candidate, 25)):
            (directory / "fixture-javadoc.jar").write_bytes(
                self.zip_bytes(f"<!-- Generated by javadoc ({version}) -->".encode()))
        documentation = C.compare(self.central, self.candidate)["artifacts"]["fixture-javadoc.jar"]
        self.assertFalse(documentation["equal"])
        self.assertEqual(documentation["changedEntries"], ["index.html"])

    @staticmethod
    def zip_bytes(content):
        output = io.BytesIO()
        with zipfile.ZipFile(output, "w") as archive:
            archive.writestr("index.html", content)
        return output.getvalue()

    def test_stale_metadata_cannot_be_blessed_by_recomputed_hashes(self):
        for directory in (self.central, self.candidate):
            self.write_module(directory)
        self.write_archive(self.candidate, content=b"different class bytes")
        with self.assertRaisesRegex(ValueError, "mismatch"):
            C.compare(self.central, self.candidate)["artifacts"]

    def test_wrong_checksum_is_rejected_even_when_size_matches(self):
        for directory in (self.central, self.candidate):
            self.write_module(directory)
        path = self.candidate / "fixture.module"
        metadata = json.loads(path.read_text())
        metadata["variants"][0]["files"][0]["sha256"] = "0" * 64
        path.write_text(json.dumps(metadata, indent=2) + "\n")
        with self.assertRaisesRegex(ValueError, "sha256 mismatch"):
            C.compare(self.central, self.candidate)["artifacts"]

    def test_pom_and_module_formatting_differences_survive(self):
        for directory in (self.central, self.candidate):
            self.write_module(directory)
            (directory / "fixture.pom").write_text("<project/>\n")
        path = self.candidate / "fixture.module"
        path.write_text(path.read_text() + "\n")
        (self.candidate / "fixture.pom").write_text("<project>changed metadata</project>\n")
        results = C.compare(self.central, self.candidate)["artifacts"]
        self.assertFalse(results["fixture.module"]["equal"])
        self.assertFalse(results["fixture.pom"]["equal"])

    def test_missing_artifact_is_rejected(self):
        (self.candidate / "fixture.jar").unlink()
        with self.assertRaisesRegex(ValueError, "file sets"):
            C.compare(self.central, self.candidate)["artifacts"]

    def test_zip_metadata_differences_survive(self):
        for field, value in (("compress_type", zipfile.ZIP_DEFLATED),
                             ("external_attr", 0o100755 << 16),
                             ("extra", b"\xfe\xca\x00\x00"), ("comment", b"entry comment"),
                             ("archive_comment", b"archive comment")):
            with self.subTest(field=field):
                for directory in (self.central, self.candidate):
                    with zipfile.ZipFile(directory / "fixture.jar", "w") as archive:
                        info = zipfile.ZipInfo("Example.class")
                        if directory == self.candidate:
                            if field == "archive_comment":
                                archive.comment = value
                            else:
                                setattr(info, field, value)
                        archive.writestr(info, b"class bytes")
                self.assertFalse(C.compare(self.central, self.candidate)["allEqual"])

    def test_normalization_never_deflates_even_for_deflated_inputs(self):
        for directory, level in ((self.central, 1), (self.candidate, 9)):
            with zipfile.ZipFile(directory / "fixture.jar", "w",
                                 compression=zipfile.ZIP_DEFLATED, compresslevel=level) as archive:
                archive.writestr("Example.class", b"repeated bytes" * 100)
            self.write_module(directory)
        with mock.patch.object(zipfile.zlib, "compressobj",
                               side_effect=AssertionError("normalization must not deflate")):
            normalized, entries = C.archive_content((self.central / "fixture.jar").read_bytes())
            self.assertEqual(entries["Example.class"][1], zipfile.ZIP_DEFLATED)
            with zipfile.ZipFile(io.BytesIO(normalized)) as archive:
                self.assertEqual(archive.getinfo("Example.class").compress_type, zipfile.ZIP_STORED)
            result = C.compare(self.central, self.candidate)
            self.assertTrue(result["allEqual"])
            hashes = result["artifacts"]["fixture.jar"]["rawSha256"]
            self.assertNotEqual(hashes["central"], hashes["candidate"])

    def test_publications_shape_is_validated(self):
        for value in ([], ["fixture"], {}, {"fixture": 1}, {"": "1.0"}):
            with self.subTest(value=value), self.assertRaisesRegex(ValueError, "publications must be"):
                C.compare(self.central, self.candidate, value)
        path = Path(self.temp.name) / "publications.json"
        path.write_text('[]')
        result = subprocess.run([sys.executable, str(Path(C.__file__)),
                                 "--central", str(self.central), "--candidate", str(self.candidate),
                                 "--output", str(Path(self.temp.name) / "output.json"),
                                 "--publications", str(path)], capture_output=True, text=True, timeout=10)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("publications must be", result.stderr)
        self.assertNotIn("AttributeError", result.stderr)

    def test_duplicate_archive_entries_are_rejected(self):
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", UserWarning)
            with zipfile.ZipFile(self.candidate / "fixture.jar", "w") as archive:
                archive.writestr("duplicate", b"one")
                archive.writestr("duplicate", b"two")
        with self.assertRaisesRegex(ValueError, "duplicate archive entry"):
            C.compare(self.central, self.candidate)

    def test_unexpected_url_record_is_rejected(self):
        self.write_module(self.candidate)
        path = self.candidate / "fixture.module"
        metadata = json.loads(path.read_text())
        metadata["variants"].append({"available-at": {"url": "other.module"}})
        path.write_text(json.dumps(metadata))
        with self.assertRaisesRegex(ValueError, "unexpected URL record"):
            C.module_content(path.read_bytes(), self.candidate)

    def test_nested_artifact_record_is_rejected(self):
        self.write_module(self.candidate)
        path = self.candidate / "fixture.module"
        metadata = json.loads(path.read_text())
        metadata["variants"][0]["files"][0]["nested"] = {"unsupported": True}
        path.write_text(json.dumps(metadata))
        with self.assertRaisesRegex(ValueError, "unsupported artifact record"):
            C.module_content(path.read_bytes(), self.candidate)

    def test_missing_metadata_fields_have_context(self):
        with self.assertRaisesRegex(ValueError, "variants list"):
            C.module_content(b"{}", self.candidate)
        self.write_module(self.candidate)
        metadata = json.loads((self.candidate / "fixture.module").read_text())
        del metadata["variants"][0]["files"][0]["size"]
        with self.assertRaisesRegex(ValueError, "integer size: fixture.jar"):
            C.module_content(json.dumps(metadata).encode(), self.candidate)

    def test_extra_artifact_is_rejected(self):
        (self.candidate / "extra.pom").write_text("<project/>")
        with self.assertRaisesRegex(ValueError, "file sets"):
            C.compare(self.central, self.candidate)

    def test_expected_set_requires_all_five_files_per_module(self):
        for directory in (self.central, self.candidate):
            (directory / "fixture.jar").rename(directory / "fixture-1.0.jar")
        with self.assertRaisesRegex(ValueError, "missing=.*fixture-1.0-javadoc.jar"):
            C.compare(self.central, self.candidate, {"fixture": "1.0"})
        for directory in (self.central, self.candidate):
            for suffix in ("-sources.jar", "-javadoc.jar"):
                (directory / f"fixture-1.0{suffix}").write_bytes(self.zip_bytes(b"content"))
            (directory / "fixture-1.0.pom").write_text("<project/>")
            (directory / "fixture-1.0.module").write_text('{"variants": []}')
        self.assertTrue(C.compare(self.central, self.candidate, {"fixture": "1.0"})["allEqual"])

    def test_cli_require_equal_writes_report_and_returns_verdict(self):
        output = Path(self.temp.name) / "report.json"
        command = [sys.executable, str(Path(C.__file__)), "--central", str(self.central),
                   "--candidate", str(self.candidate), "--output", str(output), "--require-equal"]
        self.assertEqual(subprocess.run(command, timeout=10).returncode, 0)
        self.assertTrue(json.loads(output.read_text())["allEqual"])
        self.write_archive(self.candidate, content=b"changed")
        self.assertEqual(subprocess.run(command, timeout=10).returncode, 1)
        self.assertFalse(json.loads(output.read_text())["allEqual"])
        self.assertEqual(subprocess.run(command[:-1], timeout=10).returncode, 0)


if __name__ == "__main__":
    unittest.main()
