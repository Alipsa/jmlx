  @Test
  void invFrequenciesBitMatchPinnedTorch() {
    TwoAxisRope rope = new TwoAxisRope(10_000f, 32);
    assertEquals(10_000f, rope.theta());
    assertEquals(32, rope.rotaryDims());
    float[] invFreq = rope.invFreq();
    assertEquals(16, invFreq.length);
    for (int j = 0; j < 16; j++) {
      assertEquals(
          Integer.parseUnsignedInt(PINNED_INV_FREQ_HEX[j], 16),
          Float.floatToRawIntBits(invFreq[j]),
          "invFreq[" + j + "] must bit-match the pinned torch bits");
    }
  }

  @Test
  void zeroPositionsRotateBitIdenticalToInput() {
    try (MLXScope scope = new MLXScope()) {
      int[] zero = new int[4];
      TwoAxisRope rope = new TwoAxisRope(10_000f, 32);
      TwoAxisRotation rotation = rope.prepare(scope, 4, zero, zero.clone());
      // cos must be exactly 1 and sin exactly 0 everywhere: the rotation is the identity in
      // float32 (x * 1.0 + rotate_half(x) * 0.0 is bit-exact for the positive values below).
      float[] cos = rotation.cos().toFloatArray();
      float[] sin = rotation.sin().toFloatArray();
      assertEquals(4 * 2 * 32, cos.length);
      for (float c : cos) {
        assertEquals(1.0f, c);
      }
      for (float s : sin) {
        assertEquals(0.0f, s);
      }
      float[] x = positiveValues(4 * 2 * 64);
      MLXArray arrayX = MLX.array(scope, x, new int[] {4, 2, 64});
      float[] out = rotation.rotate(arrayX).toFloatArray();
      assertEquals(x.length, out.length);
      for (int i = 0; i < x.length; i++) {
        assertEquals(
            Float.floatToRawIntBits(x[i]),
            Float.floatToRawIntBits(out[i]),
            "element " + i + " must rotate bit-identically at zero positions");
      }
    }
  }

  @Test
  void smallHandComputedCaseMatchesDoubleArithmetic() {
    int theta = 10_000;
    TwoAxisRope rope = new TwoAxisRope(theta, 4); // 2 frequencies per axis, headDim 8
    float[] invFreq = rope.invFreq();
    assertEquals(2, invFreq.length);
    assertEquals(Float.floatToRawIntBits(1.0f), Float.floatToRawIntBits(invFreq[0]));
    // invFreq[1] = theta^(-(2*1)/4) = 1 / theta^(1/2) == (float) pow(theta, -0.5): the float32
    // division by the exactly representable 100.0f rounds to the same bits as the
    // double-power-then-cast variant (verified 2026-10-21: both are 0x3c23d70a).
    assertEquals(
        Float.floatToRawIntBits((float) Math.pow(10_000.0, -0.5)),
        Float.floatToRawIntBits(invFreq[1]));
    int[] axis0 = {0, 1};
    int[] axis1 = {1, 2};
    float[] x = positiveValues(2 * 1 * 8);
    try (MLXScope scope = new MLXScope()) {
      TwoAxisRotation rotation = rope.prepare(scope, 2, axis0, axis1);
      MLXArray arrayX = MLX.array(scope, x, new int[] {2, 1, 8});
      float[] out = rotation.rotate(arrayX).toFloatArray();
      double[] invFreqDouble = {1.0, Math.pow(10_000.0, -0.5)};
      for (int i = 0; i < 2; i++) {
        for (int d = 0; d < 8; d++) {
          // emb layout [row f0, row f1, col f0, col f1, row f0, row f1, col f0, col f1].
          int halfIndex = d % 4;
          double axis = halfIndex < 2 ? axis0[i] : axis1[i];
          double v = axis * invFreqDouble[halfIndex % 2];
          double c = Math.cos(v);
          double s = Math.sin(v);
          double expected =
              d < 4
                  ? x[i * 8 + d] * c - x[i * 8 + d + 4] * s
                  : x[i * 8 + d] * c + x[i * 8 + d - 4] * s;
          assertTrue(
              Math.abs(out[i * 8 + d] - expected) <= 1e-6,
              "element (" + i + ", " + d + "): expected " + expected + ", got " + out[i * 8 + d]);
        }
      }
    }
  }

  @Test
  void cosSinMatchPinnedTorchSamplesWithinOneUlP() {
    TwoAxisRope rope = new TwoAxisRope(10_000f, 32);
    float[] invFreq = rope.invFreq();
    int bitExact = 0;
    int mismatches = 0;
    for (String[] sample : PINNED_COS_SIN) {
      int p = Integer.parseInt(sample[0]);
      int j = Integer.parseInt(sample[1]);
      int productBits = Integer.parseUnsignedInt(sample[2], 16);
      // The float32 product of the position and the component's invFreq must be the pinned v.
      assertEquals(
          productBits,
          Float.floatToRawIntBits(p * invFreq[j]),
          "product bits for (p=" + p + ", j=" + j + ") must bit-match the pinned golden");
      float v = Float.intBitsToFloat(productBits);
      int cosBits = Integer.parseUnsignedInt(sample[3], 16);
      int sinBits = Integer.parseUnsignedInt(sample[4], 16);
      float javaCos = (float) Math.cos((double) v);
      float javaSin = (float) Math.sin((double) v);
      boolean cosBit = Float.floatToRawIntBits(javaCos) == cosBits;
      boolean sinBit = Float.floatToRawIntBits(javaSin) == sinBits;
      if (cosBit && sinBit) {
        bitExact++;
      } else {
        mismatches++;
      }
      // 21 of the 24 samples are fully bit-exact; the 3 non-matching entries are (p=1, j=0),
      // (p=1, j=2) and (p=2, j=3), each a single-ulp cos difference (sin is bit-exact 24/24)
      // -- the Java-vs-torch trig gap recorded in findings §11. Every value must still be within
      // one float32 ulp (relative 2^-23, absolute 2^-23 where the pinned value is 0).
      assertWithinOneUlp(javaCos, Float.intBitsToFloat(cosBits), "cos", p, j);
      assertWithinOneUlp(javaSin, Float.intBitsToFloat(sinBits), "sin", p, j);
    }
    assertEquals(
        3,
        mismatches,
        "recorded 2026-10-21: 3 of 24 samples differ by one ulp (all cos), 21 are fully bit-exact");
    assertEquals(21, bitExact);
  }

  @Test
  void float16InputRoundTripsThroughFloat16Output() {
    try (MLXScope scope = new MLXScope()) {
      int[] axis0 = {0, 1};
      int[] axis1 = {1, 2};
      TwoAxisRope rope = new TwoAxisRope(10_000f, 4);
      TwoAxisRotation rotation = rope.prepare(scope, 2, axis0, axis1);
      float[] x = positiveValues(2 * 1 * 8);
      MLXArray arrayX = MLX.array(scope, x, new int[] {2, 1, 8});
      MLXArray half = MLX.astype(arrayX, DType.FLOAT16);
      MLXArray out = rotation.rotate(half);
      assertEquals(DType.FLOAT16, out.dtype());
      assertArrayEquals(new int[] {2, 1, 8}, out.shape());
      float[] values = out.toFloatArray();
      for (float value : values) {
        assertTrue(Float.isFinite(value), "float16 output must stay finite, got " + value);
      }
      // Loose value check against the float32 path: float16 round-trips each input and output,
      // so the worst case is well inside 2^-9 of the float32 result.
      float[] out32 = rotation.rotate(arrayX).toFloatArray();
      for (int i = 0; i < values.length; i++) {
        assertTrue(
            Math.abs(values[i] - out32[i]) <= 1e-2,
            "element " + i + ": " + values[i] + " vs float32 " + out32[i]);
      }
    }
  }

  @Test
  void constructorRejectsInvalidThetaAndRotaryDims() {
    assertThrows(IllegalArgumentException.class, () -> new TwoAxisRope(0f, 32));
    assertThrows(IllegalArgumentException.class, () -> new TwoAxisRope(-1f, 32));
    assertThrows(IllegalArgumentException.class, () -> new TwoAxisRope(Float.NaN, 32));
    assertThrows(
        IllegalArgumentException.class, () -> new TwoAxisRope(Float.POSITIVE_INFINITY, 32));
    assertThrows(
        IllegalArgumentException.class, () -> new TwoAxisRope(Float.NEGATIVE_INFINITY, 32));
    assertThrows(IllegalArgumentException.class, () -> new TwoAxisRope(10_000f, 0));
    assertThrows(IllegalArgumentException.class, () -> new TwoAxisRope(10_000f, 1));
    assertThrows(IllegalArgumentException.class, () -> new TwoAxisRope(10_000f, 3));
    assertThrows(IllegalArgumentException.class, () -> new TwoAxisRope(10_000f, -2));
  }

  @Test
  void prepareRejectsInvalidSequencesAndAxes() {
    TwoAxisRope rope = new TwoAxisRope(10_000f, 32);
    int[] axis = row(4);
    try (MLXScope scope = new MLXScope()) {
      assertThrows(
          IllegalArgumentException.class, () -> rope.prepare(scope, 0, axis, axis.clone()));
      assertThrows(IllegalArgumentException.class, () -> rope.prepare(scope, 4, null, axis));
      assertThrows(IllegalArgumentException.class, () -> rope.prepare(scope, 4, axis, null));
      assertThrows(IllegalArgumentException.class, () -> rope.prepare(scope, 4, row(3), axis));
      assertThrows(IllegalArgumentException.class, () -> rope.prepare(scope, 4, axis, row(5)));
      int[] negative = row(4);
      negative[1] = -1;
      assertThrows(IllegalArgumentException.class, () -> rope.prepare(scope, 4, negative, axis));
      assertThrows(IllegalArgumentException.class, () -> rope.prepare(scope, 4, axis, negative));
    }
  }

  @Test
  void rotateRejectsInvalidInputs() {
    TwoAxisRope rope = new TwoAxisRope(10_000f, 4); // headDim 8
    try (MLXScope scope = new MLXScope()) {
      int[] axis = row(2);
      TwoAxisRotation rotation = rope.prepare(scope, 2, axis, axis.clone());
      // wrong rank (2)
      assertThrows(
          IllegalArgumentException.class,
          () -> rotation.rotate(MLX.array(scope, positiveValues(16), new int[] {1, 16})));
      // wrong rank (4)
      assertThrows(
          IllegalArgumentException.class,
          () ->
              rotation.rotate(
                  MLX.array(scope, positiveValues(2 * 1 * 8 * 1), new int[] {2, 1, 8, 1})));
      // wrong sequence (3 rows against a 2-row rotation)
      assertThrows(
          IllegalArgumentException.class,
          () -> rotation.rotate(MLX.array(scope, positiveValues(3 * 1 * 8), new int[] {3, 1, 8})));
      // headDim mismatch (rotaryDims 4 -> headDim 8) against a 12-wide input
      assertThrows(
          IllegalArgumentException.class,
          () ->
              rotation.rotate(MLX.array(scope, positiveValues(2 * 1 * 12), new int[] {2, 1, 12})));
      assertThrows(IllegalArgumentException.class, () -> rotation.rotate(null));
    }
  }

  private static void assertWithinOneUlp(float actual, float pinned, String fn, int p, int j) {
    double limit = Math.pow(2, -23) * Math.max(1.0, Math.abs(pinned));
    assertTrue(
        Math.abs(actual - pinned) <= limit,
        fn + " for (p=" + p + ", j=" + j + "): " + actual + " vs pinned " + pinned);
  }

  /** Distinct deterministic positive values in (0, 2.34] with a per-case seed offset. */
  private static float[] positiveValues(int n) {
    float[] data = new float[n];
    for (int j = 0; j < n; j++) {
      data[j] = (((j + 1) % 7) + 1) / 3.0f;
    }
    return data;
  }

  private static int[] row(int length) {
    int[] data = new int[length];
    for (int i = 0; i < length; i++) {
      data[i] = i;
    }
    return data;
  }
